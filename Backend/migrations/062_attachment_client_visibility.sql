-- ============================================================================
-- Этап 4. Б8 (часть про вложения): признак «внутренний файл».
--
-- Правило:
--   is_internal = 0  — файл виден клиенту в портале (значение по умолчанию
--                      для всех НОВЫХ загрузок);
--   is_internal = 1  — файл виден только сотрудникам.
--
-- Галочку ставит сотрудник, у которого есть доступ к файлам этой карточки.
-- Клиентский пользователь её не видит и снять не может.
--
-- Существующие файлы помечаются внутренними: они загружались тогда, когда
-- внешнего читателя не предполагалось. Открыть их все обратно можно одним
-- запросом в конце файла.
--
-- Комментарии заявок эта миграция не трогает: по ним принято решение
-- «видны клиенту как есть», отдельного поля не требуется.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Часть 1. Проверка до изменений
-- ----------------------------------------------------------------------------

-- Ожидаем 0.
SELECT COUNT(*) AS has_is_internal
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'attachments'
  AND COLUMN_NAME = 'is_internal';

-- Сколько файлов вообще есть и по каким сущностям.
SELECT
    entity_type,
    COUNT(*) AS attachments_count,
    SUM(is_deleted = 0) AS active_count
FROM attachments
GROUP BY entity_type;

-- ----------------------------------------------------------------------------
-- Часть 2. Колонка
-- ----------------------------------------------------------------------------

ALTER TABLE attachments
    ADD COLUMN is_internal TINYINT(1) NOT NULL DEFAULT 0
        AFTER file_size;

-- Всё, что загружено до появления портала, считаем внутренним.
UPDATE attachments
SET is_internal = 1;

ALTER TABLE attachments
    ADD KEY idx_attachments_internal (is_internal);

-- ----------------------------------------------------------------------------
-- Часть 3. Проверка после изменений
-- ----------------------------------------------------------------------------

-- Ожидаем: все существующие файлы внутренние.
SELECT
    is_internal,
    COUNT(*) AS attachments_count
FROM attachments
GROUP BY is_internal;

-- Ожидаем: tinyint(1), NOT NULL, DEFAULT 0.
SELECT COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'attachments'
  AND COLUMN_NAME = 'is_internal';

