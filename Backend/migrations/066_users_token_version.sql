-- =====================================================================
-- Т2. Отзыв выданных JWT: users.token_version
--
-- Проблема. Токен живёт ACCESS_TOKEN_EXPIRE_MINUTES (сейчас 480 = 8 часов)
-- и не проверяется ни на что, кроме подписи и срока. Всё остальное уже
-- работает правильно: отключение учётки, удаление клиента и изменение
-- прав действуют на первом же запросе, потому что get_current_user
-- перечитывает пользователя из БД. Не работает ровно одно — смена
-- пароля. А это единственный сценарий, ради которого пароль и меняют:
-- учётку увели, админ поставил новый пароль, а чужая вкладка
-- продолжает работать до восьми часов.
--
-- Решение. Счётчик версии токенов на пользователе. В токен кладём
-- значение счётчика, в get_current_user сверяем. Смена пароля
-- увеличивает счётчик — все выданные раньше токены перестают
-- проходить проверку.
--
-- Почему не чёрный список jti: список надо чистить, он растёт,
-- и на каждый запрос добавляется поиск по нему. Счётчик — одно
-- целое число и одно сравнение.
--
-- DEFAULT 0 выбран намеренно: у токенов, выданных до этой миграции,
-- поля версии в payload нет, код читает его как 0, и они доживают
-- свой срок штатно. Выкатка не разлогинивает всех разом.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. ПЕРЕД ПРИМЕНЕНИЕМ. Ожидаем 0: колонки ещё нет.
-- ---------------------------------------------------------------------
SELECT COUNT(*) AS column_exists_before
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'users'
  AND COLUMN_NAME = 'token_version';


-- ---------------------------------------------------------------------
-- 2. Колонка.
-- ---------------------------------------------------------------------
ALTER TABLE users
    ADD COLUMN token_version INT NOT NULL DEFAULT 0
        COMMENT 'Версия выданных токенов. Растёт при смене пароля — гасит ранее выданные JWT';


-- ---------------------------------------------------------------------
-- 3. ПРОВЕРКА. Ожидаем: одна строка, IS_NULLABLE = NO,
--    COLUMN_DEFAULT = 0, DATA_TYPE = int.
-- ---------------------------------------------------------------------
SELECT
    COLUMN_NAME,
    DATA_TYPE,
    IS_NULLABLE,
    COLUMN_DEFAULT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'users'
  AND COLUMN_NAME = 'token_version';


-- ---------------------------------------------------------------------
-- 4. ПРОВЕРКА. Ожидаем 0: ни у кого версия не должна быть NULL
--    или отрицательной.
-- ---------------------------------------------------------------------
SELECT COUNT(*) AS broken_rows
FROM users
WHERE token_version IS NULL
   OR token_version < 0;