-- ============================================================================
-- Контактное лицо заявки.
--
-- Задача: сейчас в заявке показывается контакт из карточки КЛИЕНТА, потому
-- что своего у неё нет. На практике это разные люди: у клиента в карточке
-- сидит бухгалтер или директор, а монтажника на объекте встречает водитель
-- или завгар, и его телефон живёт в лучшем случае в комментарии.
--
-- Решение: у заявки появляется собственная пара «ФИО + телефон». При
-- создании она предзаполняется контактом клиента, но сохраняется как
-- СНИМОК: если у клиента потом сменится телефон, в старых заявках
-- останется тот, по которому реально договаривались.
--
-- Колонки NULL-able намеренно. Заявки в базе уже есть, и NOT NULL
-- пришлось бы заполнять выдумкой — решение Р51(А): у старых заявок
-- контакта нет, и интерфейс честно покажет контакт клиента с пометкой,
-- что в самой заявке он не указан.
--
-- Длины взяты как у clients.name / clients.phone, чтобы копирование
-- контакта клиента никогда не обрезалось.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- Часть 1. Проверки до изменений
-- ----------------------------------------------------------------------------

-- Ожидаем 0: колонок ещё нет.
SELECT COUNT(*) AS columns_exist_before
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'requests'
  AND COLUMN_NAME IN ('contact_name', 'contact_phone');

-- Справочно: длины полей клиента. Если они окажутся больше, чем
-- в ALTER ниже, скорректируйте — обрезка контакта при копировании
-- обнаружится не сразу и не там, где произошла.
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'clients'
  AND COLUMN_NAME IN ('name', 'phone');

-- Справочно: сколько заявок останется без собственного контакта.
SELECT COUNT(*) AS requests_total
FROM requests
WHERE is_deleted = 0;


-- ----------------------------------------------------------------------------
-- Часть 2. Колонки контакта
-- ----------------------------------------------------------------------------

ALTER TABLE requests
    ADD COLUMN contact_name VARCHAR(255) NULL
        COMMENT 'Контактное лицо ЗАЯВКИ: кого встречает монтажник. Снимок на момент создания, не ссылка на карточку клиента',
    ADD COLUMN contact_phone VARCHAR(50) NULL
        COMMENT 'Телефон контактного лица заявки. NULL у заявок, созданных до появления поля';


-- ----------------------------------------------------------------------------
-- Часть 3. Проверки после изменений
-- ----------------------------------------------------------------------------

-- Ожидаем две строки: обе NULL-able, обе без значения по умолчанию.
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, IS_NULLABLE, COLUMN_DEFAULT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'requests'
  AND COLUMN_NAME IN ('contact_name', 'contact_phone')
ORDER BY ORDINAL_POSITION;

-- Ожидаем 0: существующие заявки колонки не заполняют.
SELECT COUNT(*) AS requests_with_contact
FROM requests
WHERE contact_name IS NOT NULL
   OR contact_phone IS NOT NULL;


