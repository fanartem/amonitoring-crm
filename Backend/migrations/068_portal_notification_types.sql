    name = VALUES(name),
    description = VALUES(description),
    category = VALUES(category),
    default_enabled = VALUES(default_enabled),
    is_active = 1,
    updated_at = NOW();

-- ----------------------------------------------------------------------------
-- Часть 3. Проверка после изменений
-- ----------------------------------------------------------------------------

-- Ожидаем 7 строк, все с category = 'PORTAL' и is_active = 1.
SELECT code, name, category, default_enabled, is_active
FROM notification_types
WHERE code LIKE 'PORTAL_%'
ORDER BY id;

-- Ожидаем 0: клиентские типы не должны быть выключены персональной
-- настройкой ни у кого — этих строк ещё неоткуда взяться.
SELECT COUNT(*) AS disabled_portal_settings
FROM user_notification_settings
WHERE notification_type_code LIKE 'PORTAL_%'
  AND is_enabled = 0;

