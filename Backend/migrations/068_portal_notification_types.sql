-- ============================================================================
-- Этап 6. Типы уведомлений клиентского кабинета.
--
-- Новой таблицы не заводим: notifications, notification_types
-- и user_notification_settings подходят как есть. Нужны только строки
-- справочника — без них вставка в notifications упадёт по внешнему ключу
-- notifications_ibfk_2 (type_code → notification_types.code).
--
-- ВАЖНО: миграция применяется ДО выкладки кода. Обратный порядок даст
-- ошибку внешнего ключа на первом же событии по заявке.
--
-- category = 'PORTAL' выбран не для красоты: экран настроек уведомлений
-- сотрудника выбирает все активные типы без разбора, и без отдельной
-- категории сотрудники увидели бы у себя переключатели «Портал: ...»,
-- которые для них ничего не делают. Отсечение по категории — в патче
-- к notifications.py.
--
-- default_enabled = 1 у всех: своего экрана настроек у клиента нет,
-- и выключать ему нечем. Настройка остаётся возможной через
-- user_notification_settings, если однажды понадобится.
--
-- Про предупреждения: VALUES() внутри ON DUPLICATE KEY UPDATE в MySQL 8.0.20+
-- помечена как устаревшая, поэтому запросы вернут несколько warnings.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- Часть 1. Проверка до изменений
-- ----------------------------------------------------------------------------

-- Ожидаем 0.
SELECT COUNT(*) AS portal_types_before
FROM notification_types
WHERE code LIKE 'PORTAL_%';

-- Что уже есть — для сверки, что мы ничего не переписываем.
SELECT code, name, category, default_enabled, is_active
FROM notification_types
ORDER BY id;

