-- settings.view открывает не раздел «Настройки» (он доступен всем сотрудникам,
-- там личные настройки), а его административные вкладки.
-- Название в чеклисте доступов должно это отражать.

UPDATE permissions
SET
    name = 'Административные настройки',
    description = 'Доступ к административным вкладкам раздела «Настройки»: роли, доступы, города, уведомления. Сам раздел открыт всем сотрудникам — в нём находятся личные настройки.'
WHERE code = 'settings.view';