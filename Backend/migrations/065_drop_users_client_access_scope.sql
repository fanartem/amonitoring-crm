-- =====================================================================
-- Т3. Удаление мёртвой колонки users.client_access_scope
--
-- Колонка появилась на раннем этапе клиентского портала как задумка
-- «область доступа клиентской учётки». В итоге эту роль полностью
-- взяли на себя roles.data_scope = 'CLIENT' и право
-- portal.subclients.view: ширину видимости решает связка роли и права,
-- а не отдельное поле на пользователе.
--
-- Поиск по коду (backend + frontend) вхождений не дал — колонка
-- нигде не читается и не пишется. Мёртвое поле в users опаснее
-- обычного мусора: рано или поздно кто-то решит, что оно что-то
-- ограничивает, и построит на нём проверку доступа.
--
-- Данные не переносим: значения в колонке ни на что не влияли.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. ПЕРЕД ПРИМЕНЕНИЕМ. Ожидаем 1: колонка ещё на месте.
-- ---------------------------------------------------------------------
SELECT COUNT(*) AS column_exists_before
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'users'
  AND COLUMN_NAME = 'client_access_scope';


-- ---------------------------------------------------------------------
-- 2. Индексы, в которые входит колонка.
--    Ожидаем 0 строк. Если что-то вернётся — не применяйте миграцию
--    дальше и пришлите вывод: индекс надо снимать отдельно и осознанно.
-- ---------------------------------------------------------------------
SELECT INDEX_NAME, SEQ_IN_INDEX
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'users'
  AND COLUMN_NAME = 'client_access_scope';


-- ---------------------------------------------------------------------
-- 3. Удаление.
-- ---------------------------------------------------------------------
ALTER TABLE users
    DROP COLUMN client_access_scope;


-- ---------------------------------------------------------------------
-- 4. ПРОВЕРКА. Ожидаем 0.
-- ---------------------------------------------------------------------
SELECT COUNT(*) AS column_exists_after
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'users'
  AND COLUMN_NAME = 'client_access_scope';