-- ============================================================================
-- Настраиваемая видимость выбора времени в кабинете клиента.
--
-- Задача: у банков по договору заявка закрывается в тот же день, если она
-- создана в рабочее окно. Время в дороге учитывает диспетчер, а не клиент,
-- поэтому менеджеру банка выбирать час бессмысленно — он всё равно пишет
-- «любое».
--
-- Полностью убрать время из системы нельзя: календарь строится на времени
-- старта работ, стандартная длительность — час. Поэтому решение то же,
-- что с VIN: время не отменяется, оно перестаёт спрашиваться у клиента
-- и подставляется автоматически ближайшим РАБОЧИМ слотом
-- (см. resolve_auto_scheduled_at в requests.py).
--
-- Почему именно рабочим, а не «ближайшим доступным»: существующая
-- get_next_available_schedule_slot округляет к окну 08:00–20:00, а рабочее
-- время — пн-пт 10:00–17:30. Заявка, созданная вечером, получила бы слот
-- 08:00 следующего дня, это нерабочее время, и сервер потребовал бы
-- причину для согласования. У клиента без выбора времени такого поля нет,
-- и заявка просто не создалась бы.
--
-- Новых прав не заводим: настройка живёт в параметрах установки и
-- управляется тем же правом, что и остальные поля договора.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- Часть 1. Проверка до изменений
-- ----------------------------------------------------------------------------

-- Ожидаем 0: колонки ещё нет.
SELECT COUNT(*) AS column_exists_before
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'client_installation_settings'
  AND COLUMN_NAME = 'schedule_time_required';

-- Справочно: сколько клиентов уже имеют свои параметры установки.
-- Всем им колонка проставится в 1, то есть поведение не изменится.
SELECT COUNT(*) AS clients_with_settings
FROM client_installation_settings;


-- ----------------------------------------------------------------------------
-- Часть 2. Колонка «Клиент выбирает время»
--
-- DEFAULT 1: у всех существующих клиентов всё остаётся как было,
-- галочку снимают точечно и осознанно — как правило, банкам.
--
-- Ставим рядом с vin_required: обе колонки про одно и то же — что именно
-- клиент обязан указать при создании заявки.
-- ----------------------------------------------------------------------------

ALTER TABLE client_installation_settings
    ADD COLUMN schedule_time_required TINYINT NOT NULL DEFAULT 1
        COMMENT 'Клиент выбирает время работ. 0 — поле времени в кабинете скрыто, время подставляется ближайшим рабочим слотом'
        AFTER vin_required;


-- ----------------------------------------------------------------------------
-- Часть 3. Проверки после изменений
-- ----------------------------------------------------------------------------

-- Ожидаем одну строку: tinyint, NO, значение по умолчанию 1.
SELECT COLUMN_NAME, DATA_TYPE, IS_NULLABLE, COLUMN_DEFAULT, COLUMN_COMMENT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'client_installation_settings'
  AND COLUMN_NAME = 'schedule_time_required';

-- Ожидаем 0: ни у одного клиента выбор времени не должен пропасть
-- сам по себе при добавлении колонки.
SELECT COUNT(*) AS clients_without_time_choice
FROM client_installation_settings
WHERE schedule_time_required = 0;

-- Справочно: обе настройки рядом, чтобы видеть картину целиком.
SELECT
    client_id,
    vin_required,
    schedule_time_required
FROM client_installation_settings
ORDER BY client_id
LIMIT 20;


